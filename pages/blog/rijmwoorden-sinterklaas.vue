    <p class="leading-relaxed mb-4">
      Door de uitspraak rijmen soms woorden die er anders uitzien:
    </p>
    <ul class="list-disc pl-6 text-gray-800 space-y-2 mb-4 marker:text-red-600">
      <li>Een d aan het eind van een woord klink je als een t. Daarom rijmen paard en kaart, laat en raad, en stout en koud.</li>
      <li>Voor -je klinkt een d ook als een t. Lootje en broodje rijmen dus zuiver.</li>
      <li>Een g aan het eind klink je als ch. Dag en lach rijmen daarom op elkaar.</li>
      <li>Ei en ij klinken hetzelfde, net als au en ou. Blij rijmt op klei, en jou rijmt op blauw.</li>
    </ul>
    <p class="leading-relaxed mb-4">
      Je hebt twee vormen van rijm. Ze bepalen mee het ritme van je gedicht:
    </p>
    <ul class="list-disc pl-6 text-gray-800 space-y-2 mb-4 marker:text-red-600">
      <li><strong>Staand rijm (mannelijk)</strong>: de klemtoon valt op de allerlaatste lettergreep van de regel (zoals Sint / kind, of zoet / goed).</li>
      <li><strong>Slepend rijm (vrouwelijk)</strong>: na de beklemtoonde lettergreep volgt nog één onbeklemtoonde lettergreep (zoals pakje / zakje, of chocolade / schade).</li>
    </ul>
