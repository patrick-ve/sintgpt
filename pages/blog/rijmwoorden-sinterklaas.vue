    <h2 id="klank" class="text-3xl font-bold mt-8 mb-4">Rijm op klank: wat de spelling verbergt</h2>
    <p class="leading-relaxed mb-4">
      Rijm gaat over klank, niet over spelling. Woorden hoeven er op papier niet hetzelfde uit te zien om zuiver op elkaar te rijmen. Denk aan cadeau en zo, of Sint en kind. Vanaf de laatste beklemtoonde klinker moeten de klanken gelijk zijn. Dat noemen we <strong>volrijm</strong>.
