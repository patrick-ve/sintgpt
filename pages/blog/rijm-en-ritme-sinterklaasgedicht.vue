    <h3 class="text-2xl font-bold mt-6 mb-3">1. Stoplappen</h3>
    <p class="leading-relaxed mb-4">
      Een stoplap is een woord dat alleen in de regel staat om het ritme of het rijm te redden: "ja", "hoor", "zeker weten", "dat is waar". De lezer hoort meteen dat het opvulling is. Schrap het woord en herschrijf de regel, in plaats van hem op te vullen.
