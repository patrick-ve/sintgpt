    </p>

    <h3 class="text-2xl font-bold mt-6 mb-3">Volrijm en halfrijm</h3>
    <p class="leading-relaxed mb-4">
      <strong>Volrijm</strong> is het echte werk: klinker én medeklinkers klinken gelijk (boek / zoek). Bij <strong>halfrijm</strong> klinkt alleen de klinker gelijk (boek / doet) of alleen de medeklinkers. Halfrijm mag af en toe, vooral in een modern of ironisch gedicht. In een sinterklaasgedicht verwacht het publiek volrijm, dus gebruik halfrijm met mate.
    </p>
    <p class="leading-relaxed mb-4">
