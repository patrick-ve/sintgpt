    </p>

    <h3 class="text-2xl font-bold mt-6 mb-3">Staand en slepend rijm</h3>
    <ul class="list-disc pl-6 text-gray-800 space-y-2 mb-4 marker:text-red-600">
      <li><strong>Staand rijm</strong> eindigt op een beklemtoonde lettergreep: vuur / uur, pan / kan. Dit klinkt stevig en afgerond. Het is ideaal voor een punchline.</li>
      <li><strong>Slepend rijm</strong> eindigt op een beklemtoonde en dan een onbeklemtoonde lettergreep: koken / roken, Pietje / liedje. Dit klinkt zachter en loopt door.</li>
    </ul>
    <p class="leading-relaxed mb-4">
